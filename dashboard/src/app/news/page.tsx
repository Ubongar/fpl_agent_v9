"use client";

import { useState } from "react";
import { newsBriefing } from "@/lib/api";
import { EmptyState, Panel } from "@/components/ui";

export default function NewsPage() {
  const [entryId, setEntryId] = useState("");
  const [briefing, setBriefing] = useState<string | null>(null);
  const [loading, setLoading] = useState(false);
  const [error, setError] = useState<string | null>(null);

  const handleFetch = async () => {
    if (!entryId) {
      alert("Please enter your FPL ID");
      return;
    }
    setLoading(true);
    setError(null);
    setBriefing(null);
    
    try {
      // Pass the entry ID to the backend
      const res = await fetch(`/api/news/briefing?entry_id=${entryId}`);
      if (!res.ok) {
        const body = await res.json();
        throw new Error(body.detail || "Failed to fetch briefing");
      }
      const data = await res.json();
      setBriefing(data.briefing);
    } catch (e) {
      setError(e instanceof Error ? e.message : "Could not load news briefing.");
    } finally {
      setLoading(false);
    }
  };

  return (
    <div className="space-y-5 max-w-4xl mx-auto">
      <div>
        <div className="text-[10px] uppercase tracking-[0.18em] text-[var(--accent)]">Live Intelligence</div>
        <h1 className="mt-2 text-3xl font-semibold tracking-tight">Manager Briefing</h1>
        <p className="mt-2 text-sm leading-6 text-muted">
          Get an AI-generated tactical analysis of your FPL squad. We combine the latest league-wide injury news with your specific team's projections to tell you who to sell, who to buy, and who to captain.
        </p>
      </div>

      <div className="flex items-center gap-3 rounded-xl border border-line bg-panel/50 p-4">
        <input
          type="number"
          placeholder="Enter your FPL ID (e.g. 1234567)"
          value={entryId}
          onChange={(e) => setEntryId(e.target.value)}
          className="flex-1 rounded-lg border border-line bg-bg px-3 py-2 text-sm text-fg focus:border-[var(--accent)] focus:outline-none"
        />
        <button
          onClick={handleFetch}
          disabled={loading || !entryId}
          className="rounded-lg bg-[var(--accent)] px-4 py-2 text-sm font-semibold text-black hover:opacity-90 disabled:opacity-50 transition-opacity"
        >
          {loading ? "Analyzing..." : "Generate Briefing"}
        </button>
      </div>

      {error && (
        <EmptyState title="Briefing Unavailable" detail={error} command="Check your .env or terminal for details." />
      )}

      {briefing && (
        <Panel title="Your Tactical Briefing" subtitle="Generated by Groq LLM based on your squad and current news.">
          <div className="prose prose-invert max-w-none text-sm leading-7 whitespace-pre-wrap font-sans">
            {briefing}
          </div>
        </Panel>
      )}
    </div>
  );
}